/**
 * Assemble one publishable package out of the engineering components.
 *
 * Each component keeps its own directory tree under `vendor/`. Flattening them
 * into a shared `lib/` would break the relative lookups the modules already do -
 * a skill module resolves `../SKILL.md` from its own package root, and the
 * Studio bridge and MotionWorks engine resolve their asset folders the same way.
 * Keeping the tree means those paths stay true with no source edits.
 */
import { cp, mkdir, readdir, rm, stat } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const VENDOR = join(ROOT, 'vendor')

/** Component packages, in build order. Optix arrives built (no source of ours). */
export const COMPONENTS = [
  "l5x",
  "ftview",
  "mwi",
  "resources",
  "optix",
  "migration",
  "ecad",
  "plc5"
]

/** The newest modification time under a directory, or undefined when it is absent. */
async function newest(directory) {
  let latest
  for (const entry of await readdir(directory, { withFileTypes: true }).catch(() => [])) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) {
      const below = await newest(path)
      if (below && (!latest || below.time > latest.time)) latest = below
      continue
    }
    const info = await stat(path).catch(() => undefined)
    if (info && (!latest || info.mtimeMs > latest.time)) latest = { time: info.mtimeMs, path }
  }
  return latest
}

/** Copy one component's built tree into the vendored layout. */
async function vendor(name) {
  const from = join(ROOT, 'packages', name)
  const to = join(VENDOR, name)
  const built = await stat(join(from, 'lib', 'index.js')).catch(() => undefined)
  if (built === undefined) throw new Error(`${name}: build it first (pnpm --filter @aryacode/dsh-engineering-${name} build)`)
  // `lib/` is gitignored build output, so nothing in git notices when it is
  // older than the sources it is vendored from. That is not theoretical: the
  // 0.4.20 market tarball shipped the 0.4.16 MotionWorks build under a 0.4.20
  // version because assemble copied a stale lib/. Refuse instead of shipping.
  //
  // The comparison uses the newest built file, not lib/index.js: an ECAD face
  // change rebuilds only `lib/client.js`, and comparing against index.js would
  // refuse a correctly rebuilt tree.
  const source = await newest(join(from, 'src'))
  const newestBuilt = await newest(join(from, 'lib'))
  if (source !== undefined && newestBuilt !== undefined && source.time > newestBuilt.time) {
    throw new Error(
      `${name}: lib/ is older than ${source.path.replace(ROOT, '.')}; rebuild before packing ` +
      `(pnpm --filter @aryacode/dsh-engineering-${name} build)`,
    )
  }
  await rm(to, { recursive: true, force: true })
  await mkdir(to, { recursive: true })
  // `templates`, `locale` and `icon.svg` belong to the Optix tree; `bin`, `rust`
  // and `THIRD_PARTY_NOTICES.md` belong to the ECAD tree (its DWG converter and
  // the MPL/MIT notices). A missing entry is skipped, so one list serves every
  // component.
  //
  // Python bytecode is never vendored: `__pycache__` is generated by whatever
  // interpreter last ran in the checkout, it is not source, and a stale `.pyc`
  // beside an edited module is a trap the engine does not need. 0.4.21 shipped
  // three of them because a `py_compile` check ran before packing.
  //
  // `skills` is the Optix topic playbooks `optix_get_skill` reads. It was missing
  // from this list through 0.99.0, so the published tarball carried
  // `vendor/optix/lib/skills.js` but no `vendor/optix/skills/`: the module resolved
  // `../skills` into an absent directory, `optix_list_skills` answered with an empty
  // list and `optix_get_skill` refused every topic. A payload a component resolves
  // at runtime has to be in this list or the tool that reads it ships broken, which
  // is what `test/components.spec.mjs` now checks by name.
  for (const entry of ['lib', 'assets', 'bin', 'rust', 'THIRD_PARTY_NOTICES.md', 'SKILL.md', 'README.md', 'LICENSE-CONTENT.md', 'corpus', 'index.json', 'SOURCE.json', 'studio-bridge', 'bridge', 'code', 'legacy', 'netlogic', 'schema', 'help', 'poll-worker.mjs', 'cip-worker.mjs', 'templates', 'skills', 'locale', 'icon.svg']) {
    const source = join(from, entry)
    // An absent entry is expected: one list serves every component. Any other
    // failure is not - `cp(...).catch(() => {})` used to swallow both, which is
    // how a payload a tool resolves at runtime (optix `skills/`, through 0.99.0)
    // could be missing from the tarball while assemble reported success.
    const present = await stat(source).then(
      () => true,
      error => {
        if (error.code === 'ENOENT') return false
        throw error
      },
    )
    if (present === false) continue
    await cp(source, join(to, entry), {
      recursive: true,
      filter: s => !s.includes('__pycache__') && !s.endsWith('.pyc') && (!s.endsWith('.ts') || s.endsWith('.d.ts')),
    })
  }
}

await rm(VENDOR, { recursive: true, force: true })
for (const name of COMPONENTS) await vendor(name)
console.log(`assembled ${COMPONENTS.length} components into vendor/`)
